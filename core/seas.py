def sea_name(lat: float, lon: float) -> str:
    """返回海域名；不在表内则返回坐标描述。"""
    for name, minlat, minlon, maxlat, maxlon in _SEAS:
        if minlat <= lat <= maxlat and minlon <= lon <= maxlon:
            return name
    ns = "N" if lat >= 0 else "S"
    ew = "E" if lon >= 0 else "W"
    return f"{abs(lat):.0f}°{ns} {abs(lon):.0f}°{ew}"


def describe(lat: float, lon: float) -> str:
    """带象限的方向描述，例如「东海北部」「北海西南部」。"""
    base = sea_name(lat, lon)
    for name, minlat, minlon, maxlat, maxlon in _SEAS:
        if name != base:
            continue
        dy = lat - (minlat + maxlat) / 2
        dx = lon - (minlon + maxlon) / 2
        if abs(dy) < 1.2 and abs(dx) < 1.2:
            return base
        v = "北" if dy > 0 else "南"
        h = "东" if dx > 0 else "西"
        if abs(dy) < 1.2:
            return f"{base}{h}部"
        if abs(dx) < 1.2:
            return f"{base}{v}部"
        return f"{base}{v}{h}部"
    return base
